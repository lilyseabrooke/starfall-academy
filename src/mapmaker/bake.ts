/* ===========================================================================
   Mapmaker — bake a `.map.json` into the TypeScript module main ships.
   Pure (no fs) so the /mapmaker page can show the exact module text too.
   =========================================================================== */
import type { MapJson } from "./format";
import { jsonToAtlas } from "./convert";
import { formatValue } from "./stringify";

export const GENERATED_MARK = "@generated by scripts/bake-map.ts";

export const atlasConstName = (id: string) => id.toUpperCase().replace(/[^A-Z0-9]+/g, "_") + "_ATLAS";

export function bakeModule(m: MapJson): string {
  const atlas = jsonToAtlas(m);
  return `/* ===========================================================================
   Starfall Atlas — ${m.name} (${m.id}).
   ${GENERATED_MARK} from maps/${m.id}.map.json on the
   staging/mapmaking branch. Do not edit by hand: change the map in /mapmaker,
   re-bake, and copy this file to main.
   =========================================================================== */
import type { AtlasDefinition } from "../types";

export const ${atlasConstName(m.id)}: AtlasDefinition = ${formatValue(atlas)};
`;
}
